#!/usr/bin/env python3
"""Generates fixture_db.h: a tiny, made-up iTunesDB in the layout dbwriter understands
(no real library data in it). The C tests embed the bytes, so `make test` needs no iPod file."""
import struct, random
random.seed(5)
u32 = lambda v: struct.pack('<I', v)
u64 = lambda v: struct.pack('<Q', v)
def pad(b, n): return b + bytes(n - len(b))

def mhod_str(t, s):
    d = s.encode('utf-16le')
    return b'mhod' + u32(24) + u32(40 + len(d)) + u32(t) + u32(0) + u32(0) + u32(1) + u32(len(d)) + u32(1) + u32(0) + d

TRACKS = [  # title, artist, album, genre
    ("Alpha Song", "Artist One", "First Album", ""),
    ("Bravo Tune", "Artist One", "First Album", ""),
    ("Charlie Beat", "Artist Two", "Second Album", ""),
    ("Delta Drift", "Artist Two", "Second Album", ""),
    ("Echo Place", "Artist Three", "Third Album", ""),
]
albums = []
for t in TRACKS:
    if (t[2], t[1]) not in albums: albums.append((t[2], t[1]))
artists = []
for t in TRACKS:
    if t[1] not in artists: artists.append(t[1])

album_id = {a: 570 + i for i, a in enumerate(albums)}
artist_id = {a: 9089 + i for i, a in enumerate(artists)}
LIB = 0x4b9dd7e1b4172b57

def mhia(i, a):
    body = mhod_str(200, a[0]) + mhod_str(201, a[1])
    hdr = b'mhia' + u32(88) + u32(88 + len(body)) + u32(2) + u32(album_id[a]) + u64(random.getrandbits(64)) + u32(2) + u64(0) + u32(0) + u32(0)
    return pad(hdr, 88) + body

tr = []
dbids = []
for i, (title, artist, album, genre) in enumerate(TRACKS):
    tid = 856 + 2 * i
    dbid = random.getrandbits(64); dbids.append(dbid)
    h = bytearray(624)
    h[0:4] = b'mhit'; h[4:8] = u32(624); h[12:16] = u32(6); h[16:20] = u32(tid); h[20:24] = u32(1)
    h[24:28] = u32(0x4d503320); h[28:32] = u32(0x100); h[32:36] = u32(0xe6be1e8c)
    h[36:40] = u32(4000000 + i); h[40:44] = u32(200000 + i); h[44:48] = u32(i + 1); h[56:60] = u32(160)
    h[60:64] = u32(44100 << 16); h[104:108] = u32(0xe6db33f0); h[112:120] = u64(dbid); h[124:128] = u32(0xffff0000)
    h[136:140] = struct.pack('<f', 44100.0); h[144:148] = u32(0xc); h[164:168] = u32(2); h[168:176] = u64(dbid)
    h[176:180] = u32(0x20000); h[204:208] = u32(0x2000003); h[288:292] = u32(album_id[(album, artist)])
    h[292:300] = u64(LIB); h[300:304] = u32(4000000 + i); h[308:312] = u32(0x80808080); h[312:316] = u32(0x8080)
    h[480:484] = u32(artist_id[artist]); h[500:504] = u32(tid + 1)
    body = (mhod_str(1, title) + mhod_str(4, artist) + mhod_str(22, artist) + mhod_str(3, album) +
            mhod_str(6, "MP3") + mhod_str(2, ":iPod_Control:Music:F0%d:AB%02d.mp3" % (i % 3, i)))
    h[8:12] = u32(624 + len(body))
    tr.append(bytes(h) + body)

N = len(TRACKS)
def order(key): return sorted(range(N), key=lambda i: key(TRACKS[i]).lower())
sorts = [(3, order(lambda t: t[0])), (4, order(lambda t: t[2])), (5, order(lambda t: t[1])), (7, order(lambda t: t[3])),
         (18, list(range(N))), (35, order(lambda t: t[1])), (36, order(lambda t: t[1]))]
def mhod52(st, arr):
    return b'mhod' + u32(24) + u32(72 + 4 * N) + u32(52) + bytes(8) + u32(st) + u32(N) + bytes(40) + b''.join(u32(v) for v in arr)

def playlist_section(typ):
    mhods = mhod_str(1, "Library") + pad(b'mhod' + u32(24) + u32(648) + u32(100), 648) + pad(b'mhod' + u32(24) + u32(356) + u32(102), 356)
    mhods += b''.join(mhod52(st, a) for st, a in sorts)
    ips = b''
    for i in range(N):
        ip = bytearray(120)
        ip[0:4] = b'mhip'; ip[4:8] = u32(76); ip[8:12] = u32(120); ip[12:16] = u32(1)
        ip[20:24] = u32(6342 + i); ip[24:28] = u32(856 + 2 * i); ip[28:32] = u32(0xe6db33f0); ip[44:52] = u64(dbids[i])
        ip[60:68] = u64(random.getrandbits(64)); ip[76:80] = b'mhod'; ip[80:84] = u32(24); ip[84:88] = u32(44)
        ip[88:92] = u32(100); ip[100:104] = u32(i)
        ips += bytes(ip)
    yp = pad(b'mhyp' + u32(184) + u32(184 + len(mhods) + len(ips)) + u32(10) + u32(N), 184) + mhods + ips
    lp = pad(b'mhlp' + u32(92) + u32(1), 92) + yp
    return pad(b'mhsd' + u32(96) + u32(96 + len(lp)) + u32(typ), 96) + lp

def section(typ, lst_tag, items):
    lst = pad(lst_tag + u32(92) + u32(len(items)), 92) + b''.join(items)
    return pad(b'mhsd' + u32(96) + u32(96 + len(lst)) + u32(typ), 96) + lst

sec4 = section(4, b'mhla', [mhia(i, a) for i, a in enumerate(albums)])
sec1 = section(1, b'mhlt', tr)
sec5 = section(5, b'mhlp', [])
secs = sec4 + sec1 + playlist_section(3) + playlist_section(2) + sec5
mhbd = bytearray(244); mhbd[0:4] = b'mhbd'; mhbd[4:8] = u32(244); mhbd[8:12] = u32(244 + len(secs))
mhbd[12:16] = u32(1); mhbd[16:20] = u32(0x73); mhbd[20:24] = u32(5); mhbd[70:72] = b'en'
data = bytes(mhbd) + secs

with open('fixture_db.h', 'w') as f:
    f.write("// Generated by make_fixture.py: a tiny made-up iTunesDB (5 tracks, 3 albums) for the tests.\n")
    f.write("static const unsigned char fixture_db[] = {\n")
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join("0x%02x" % b for b in data[i:i+16]) + ",\n")
    f.write("};\n")
print("fixture_db.h:", len(data), "bytes")
